const normalizeLang = (lang) => (permissionLabels[lang] ? lang : 'uz');

export const getAdminPermissionLabels = (lang = 'uz') =>
  permissionLabels[normalizeLang(lang)];

export const getAdminPermissionText = (lang = 'uz', key) =>
  (permissionUiText[normalizeLang(lang)] || permissionUiText.uz)[key] ||
  permissionUiText.uz[key] ||
  key;

export const normalizeAdminPermissions = (value) => ({
  ...ADMIN_PERMISSION_DEFAULTS,
  ...(value && typeof value === 'object' ? value : {}),
});

export const canUsePermission = (permissions, key) =>
  normalizeAdminPermissions(permissions)[key] !== false;
