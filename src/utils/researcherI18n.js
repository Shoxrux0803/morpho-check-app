const DEFAULT_LANGUAGE = "en";

const normalizeResearcherLang = (lang) => {
  const code = String(lang || DEFAULT_LANGUAGE)
    .toLowerCase()
    .split(/[-_]/)[0];
  return dictionaries[code] ? code : DEFAULT_LANGUAGE;
};

export const researcherT = (lang, key) =>
  dictionaries[normalizeResearcherLang(lang)]?.[key] ??
  dictionaries[DEFAULT_LANGUAGE]?.[key] ??
  key;

export const researcherOption = (lang, key) => researcherT(lang, key);
